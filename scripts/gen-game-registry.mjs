/**
 * Generates everything that names the platform's games from the one list in
 * platform.games.json:
 *
 *   packages/web/src/platform.games.ts      every game's GameDefinition, in order
 *   packages/server/src/games/registry.ts   server rules of games with a ./server entry
 *   packages/web/package.json               @canvas/games-* dependencies
 *   packages/web/tsconfig.json              @canvas/games-* paths and project references
 *   packages/server/package.json            @canvas/games-* dependencies (multiplayer only)
 *
 *   node scripts/gen-game-registry.mjs           write the files
 *   node scripts/gen-game-registry.mjs --check   fail if any of them is stale (CI)
 *
 * A game has server rules when its package.json exports "./server"; that
 * entry default-exports a ServerSystem (a multiplayer GameRoom game), or a
 * RunSystem (a single-player run in a RunRoom) when its package.json says
 * `"canvas": {"serverKind": "run"}`.
 */
import {existsSync, readFileSync, writeFileSync} from 'node:fs';
import {dirname, join, relative, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');

const readJson = (path) => JSON.parse(readFileSync(join(root, path), 'utf8'));
const formatJson = (value) => JSON.stringify(value, null, 2) + '\n';

// ── Read and validate the list ───────────────────────────────────────────────

const {games: ids} = readJson('platform.games.json');
const problems = [];
if (!Array.isArray(ids) || ids.length === 0) problems.push('"games" must be a non-empty array');
if (new Set(ids).size !== ids.length) problems.push('"games" lists a game twice');

const games = (Array.isArray(ids) ? ids : []).map((id) => {
  const pkgPath = `packages/games/${id}/package.json`;
  if (!/^[a-z][a-z0-9-]*$/.test(id)) problems.push(`"${id}" is not a valid game id`);
  if (!existsSync(join(root, pkgPath))) {
    problems.push(`"${id}": ${pkgPath} doesn't exist`);
    return {id};
  }
  const pkg = readJson(pkgPath);
  const name = `@canvas/games-${id}`;
  if (pkg.name !== name) problems.push(`"${id}": ${pkgPath} is named ${pkg.name}, expected ${name}`);
  const server = Boolean(pkg.exports?.['./server']);
  const kind = pkg.canvas?.serverKind ?? 'room';
  if (!['room', 'run'].includes(kind)) problems.push(`"${id}": canvas.serverKind must be "room" or "run"`);
  return {id, name, server, kind};
});

if (problems.length) {
  console.error('✗ platform.games.json:');
  for (const p of problems) console.error(`  ${p}`);
  process.exit(1);
}

const serverGames = games.filter((g) => g.server);
const roomGames = serverGames.filter((g) => g.kind === 'room');
const runGames = serverGames.filter((g) => g.kind === 'run');
// `sudoku` -> `sudoku`, `tic-tac-toe` -> `ticTacToe`: a valid identifier per game.
const ident = (id) => id.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const HEADER = '// GENERATED by scripts/gen-game-registry.mjs from platform.games.json — do not edit.\n';

// ── Generated files ──────────────────────────────────────────────────────────

const outputs = new Map();

outputs.set(
  'packages/web/src/platform.games.ts',
  HEADER +
    `/**
 * The games this platform builds in, in home-page order. Each entry is a game
 * package's \`GameDefinition\` (manifest + \`register()\`). Edit
 * platform.games.json at the repo root, then run \`pnpm games:gen\`.
 */
import type {GameDefinition} from '@canvas/engine';
${games.map((g) => `import ${ident(g.id)} from '${g.name}';`).join('\n')}

export const PLATFORM_GAMES: readonly GameDefinition[] = [${games.map((g) => ident(g.id)).join(', ')}];
`
);

outputs.set(
  'packages/server/src/games/registry.ts',
  HEADER +
    `import type {RunSystem, ServerSystem} from '../types';
${serverGames.map((g) => `import ${ident(g.id)} from '${g.name}/server';`).join('\n')}

/**
 * Map of \`serverSystem\` name -> ServerSystem implementation, for every game
 * in platform.games.json whose package exports \`./server\` for a GameRoom.
 */
export const serverSystemRegistry = new Map<string, ServerSystem>([
${roomGames.map((g) => `  [${ident(g.id)}.systemName, ${ident(g.id)} as ServerSystem],`).join('\n')}
]);

/**
 * Map of game id -> RunSystem, for every game whose \`./server\` runs
 * single-player runs in a RunRoom (\`"canvas": {"serverKind": "run"}\`).
 */
export const runSystemRegistry = new Map<string, RunSystem>([
${runGames.map((g) => `  ['${g.id}', ${ident(g.id)} as RunSystem],`).join('\n')}
]);

if (serverSystemRegistry.size !== ${roomGames.length}) {
  throw new Error('Two games share a ServerSystem systemName');
}
`
);

/** Replaces a package.json's @canvas/games-* dependencies with `names`, keeping the rest. */
function withGameDeps(path, names) {
  const pkg = readJson(path);
  const deps = Object.fromEntries(
    Object.entries(pkg.dependencies ?? {}).filter(([dep]) => !dep.startsWith('@canvas/games-'))
  );
  for (const name of names) deps[name] = 'workspace:*';
  pkg.dependencies = Object.fromEntries(Object.entries(deps).sort(([a], [b]) => a.localeCompare(b)));
  return formatJson(pkg);
}

outputs.set('packages/web/package.json', withGameDeps('packages/web/package.json', games.map((g) => g.name)));
outputs.set('packages/server/package.json', withGameDeps('packages/server/package.json', serverGames.map((g) => g.name)));

{
  const path = 'packages/web/tsconfig.json';
  const tsconfig = readJson(path);
  const paths = Object.fromEntries(
    Object.entries(tsconfig.compilerOptions.paths ?? {}).filter(([k]) => !k.startsWith('@canvas/games-'))
  );
  for (const g of games) paths[g.name] = [`../../games/${g.id}/src/index.ts`];
  tsconfig.compilerOptions.paths = paths;
  tsconfig.references = [
    ...(tsconfig.references ?? []).filter((r) => !r.path.startsWith('../games/')),
    ...games.map((g) => ({path: `../games/${g.id}`})),
  ];
  outputs.set(path, formatJson(tsconfig));
}

// ── Write or check ───────────────────────────────────────────────────────────

const stale = [...outputs].filter(([path, text]) => {
  const full = join(root, path);
  return !existsSync(full) || readFileSync(full, 'utf8') !== text;
});

if (check) {
  if (stale.length) {
    console.error('✗ Generated game files are out of date with platform.games.json:');
    for (const [path] of stale) console.error(`  ${path}`);
    console.error('Run `pnpm games:gen` and commit the result.');
    process.exit(1);
  }
  console.log(
    `✓ game files match platform.games.json (${games.length} games, ${roomGames.length} multiplayer, ${runGames.length} with runs)`
  );
} else {
  for (const [path, text] of stale) writeFileSync(join(root, path), text);
  console.log(
    stale.length
      ? `Updated ${stale.map(([p]) => relative(root, join(root, p))).join(', ')}`
      : 'Already up to date'
  );
  if (stale.some(([p]) => p.endsWith('package.json'))) console.log('Dependencies changed: run `pnpm install`.');
}
